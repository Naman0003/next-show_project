create function t.chk(name text, ok boolean) returns void language sql as
  $$ insert into t.results(name, ok) values (name, coalesce(ok, false)) $$;

create function t.become(who text) returns void language plpgsql as $$
declare i record;
begin
  reset role;
  perform set_config('request.jwt.claim.sub', '', true);
  perform set_config('request.jwt.claims', '{}', true);
  if who = 'super' then return; end if;
  if who = 'anon' then set local role anon; return; end if;
  select * into i from t.ids where name = who;
  perform set_config('request.jwt.claim.sub', i.id::text, true);
  perform set_config('request.jwt.claims',
    json_build_object('sub', i.id, 'email', i.email, 'role', 'authenticated')::text, true);
  set local role authenticated;
end $$;

