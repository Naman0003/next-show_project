-- Security regression tests for security_fixes.md (S1, S2, S3, S4, S12).
-- Run on a THROWAWAY database only (see supabase/tests/README.md). Everything rolls back.
-- Prints one row per check; any `FAIL` row means a vulnerability or a broken legit flow.

begin;

create schema t;
grant usage on schema t to public;
create table t.results (n serial, name text, ok boolean);
create table t.ids (name text primary key, id uuid, email text);
grant all on t.results, t.ids to public;
grant usage on all sequences in schema t to public;

create function t.chk(name text, ok boolean) returns void language sql as
  $$ insert into t.results(name, ok) values (name, coalesce(ok, false)) $$;

create function t.become(who text) returns void language plpgsql as $$
declare i record;
begin
  reset role;
  perform set_config('request.jwt.claim.sub', '', true);
  perform set_config('request.jwt.claims', '{}', true);
  if who = 'super' then return; end if;
  if who = 'anon' then set local role anon; return; end if;
  select * into i from t.ids where name = who;
  perform set_config('request.jwt.claim.sub', i.id::text, true);
  perform set_config('request.jwt.claims',
    json_build_object('sub', i.id, 'email', i.email, 'role', 'authenticated')::text, true);
  set local role authenticated;
end $$;

---------------------------------------------------------------- fixtures (superuser)
insert into t.ids select n, gen_random_uuid(), n || '@x.com'
from unnest(array['attacker','owner','invitee','partner_a','partner_b','admin','orphan','victim','unverified']) n;

insert into auth.users (id, email, raw_user_meta_data)
select id, email, '{}' from t.ids;               -- signup trigger creates the profiles

delete from public.profiles where id = (select id from t.ids where name = 'orphan');
update public.profiles set role = 'partner', is_verified = true
  where id in (select id from t.ids where name in ('owner', 'partner_a', 'partner_b'));
update public.profiles set role = 'admin' where id = (select id from t.ids where name = 'admin');

insert into public.venues (id, owner_id, name, venue_type)
select gen_random_uuid(), id, 'Venue ' || name, 'cinema' from t.ids where name = 'owner';

insert into public.organizer_invites (venue_id, invited_by, email, role, token)
select v.id, v.owner_id, 'invitee@x.com', 'owner', 'tok_known' from public.venues v;

insert into public.tickets (user_id, event_title, venue_name, starts_at, ticket_code)
select id, 'Film', 'Venue', now() + interval '1 day', 'CODE-' || name from t.ids where name in ('victim', 'attacker');

---------------------------------------------------------------- S1: signup metadata
insert into auth.users (id, email, raw_user_meta_data)
values ('00000000-0000-0000-0000-0000000000aa', 'evil@x.com', '{"role":"admin"}');
select t.chk('S1 signup with metadata role=admin yields a plain user',
  (select role = 'user' from public.profiles where id = '00000000-0000-0000-0000-0000000000aa'));

---------------------------------------------------------------- S2: profile email / invites
select t.become('attacker');
update public.profiles set email = 'invitee@x.com' where id = (select id from t.ids where name = 'attacker');
select t.become('super');
select t.chk('S2 client cannot change profiles.email',
  (select email = 'attacker@x.com' from public.profiles where id = (select id from t.ids where name = 'attacker')));

select t.become('attacker');
select t.chk('S2 attacker cannot read invites addressed to someone else',
  (select count(*) = 0 from public.organizer_invites));

do $$ declare tok text; begin
  perform t.become('owner');
  insert into public.organizer_invites (venue_id, invited_by, email, role)
    select id, owner_id, 'new@x.com', 'editor' from public.venues limit 1 returning token into tok;
  perform t.become('super');
  perform t.chk('S2 owner can invite; token is generated by the DB (64+ chars)', length(tok) >= 64);
exception when others then
  perform t.become('super');
  perform t.chk('S2 owner can invite; token is generated by the DB (error: ' || sqlerrm || ')', false);
end $$;

do $$ declare owner_after uuid; owner_before uuid; begin
  perform t.become('super');
  select owner_id into owner_before from public.venues limit 1;
  perform t.become('attacker');
  begin perform public.accept_organizer_invite('tok_known'); exception when others then null; end;
  perform t.become('super');
  select owner_id into owner_after from public.venues limit 1;
  perform t.chk('S2 attacker cannot take a venue with a leaked token', owner_after = owner_before);
end $$;

do $$ declare ok boolean; begin
  perform t.become('invitee');
  perform public.accept_organizer_invite('tok_known');
  perform t.become('super');
  select (v.owner_id = (select id from t.ids where name = 'invitee')) and i.accepted_at is not null
    into ok from public.venues v, public.organizer_invites i where i.token = 'tok_known';
  perform t.chk('S2 the invited user can still accept their invite', ok);
exception when others then
  perform t.become('super');
  perform t.chk('S2 the invited user can still accept their invite (error: ' || sqlerrm || ')', false);
end $$;

do $$ declare code text; begin
  perform t.become('anon');
  begin perform public.accept_organizer_invite('whatever'); code := 'none';
  exception when others then code := sqlstate; end;
  perform t.become('super');
  perform t.chk('S12 anon cannot execute accept_organizer_invite (got ' || code || ')', code = '42501');
end $$;

update auth.users set email = 'changed@x.com' where id = (select id from t.ids where name = 'victim');
select t.chk('S2 auth email change flows into profiles.email',
  (select email = 'changed@x.com' from public.profiles where id = (select id from t.ids where name = 'victim')));

---------------------------------------------------------------- S4: profiles insert
do $$ declare code text; begin
  perform t.become('orphan');
  begin
    insert into public.profiles (id, email, role)
      values ((select id from t.ids where name = 'orphan'), 'orphan@x.com', 'admin');
    code := 'inserted';
  exception when others then code := sqlstate; end;
  perform t.become('super');
  perform t.chk('S4 client cannot insert its own (admin) profile (got ' || code || ')', code = '42501');
end $$;

---------------------------------------------------------------- profile role guard (must keep working)
select t.become('attacker');
update public.profiles set role = 'admin' where id = (select id from t.ids where name = 'attacker');
select t.become('super');
select t.chk('user cannot self-promote to admin',
  (select role = 'user' from public.profiles where id = (select id from t.ids where name = 'attacker')));

---------------------------------------------------------------- S3: events
do $$ declare ev uuid; n int; ok boolean; begin
  perform t.become('partner_a');
  insert into public.events (category, title) values ('movie', 'A film') returning id into ev;
  update public.events set title = 'A film (edited)' where id = ev;
  get diagnostics n = row_count;
  perform t.chk('S3 partner can edit their own event', n = 1);

  perform t.become('partner_b');
  update public.events set title = 'hacked', status = 'cancelled' where id = ev;
  get diagnostics n = row_count;
  perform t.chk('S3 another partner cannot edit it', n = 0);

  perform t.become('partner_a');
  update public.events set is_verified = true where id = ev;
  perform t.become('super');
  perform t.chk('S3 partner cannot self-verify via update',
    (select is_verified = false from public.events where id = ev));

  perform t.become('admin');
  update public.events set title = 'moderated' where id = ev;
  get diagnostics n = row_count;
  perform t.chk('S3 admin can edit any event', n = 1);
end $$;

do $$ declare a boolean; b boolean; begin
  perform t.become('partner_a');
  insert into public.events (category, title, is_verified) values ('movie', 'Fake verified', true)
    returning is_verified into a;
  insert into public.events (category, title, is_verified, external_ids)
    values ('movie', 'TMDB film', true, '{"tmdb_id":"603"}') returning is_verified into b;
  perform t.become('super');
  perform t.chk('S3 partner cannot insert a pre-verified custom event', a = false);
  perform t.chk('S3 TMDB-sourced event keeps verified flag (organizer flow)', b = true);
exception when others then
  perform t.become('super');
  perform t.chk('S3 event insert flows (error: ' || sqlerrm || ')', false);
end $$;

---------------------------------------------------------------- tickets / anon reads (live table, sanity)
select t.become('attacker');
select t.chk('tickets: user sees no one else''s tickets',
  (select count(*) = 1 and bool_and(ticket_code = 'CODE-attacker') from public.tickets));
select t.become('anon');
select t.chk('anon cannot read profiles', (select count(*) = 0 from public.profiles));
select t.chk('anon can read v_listings', (select count(*) >= 0 from public.v_listings));
---------------------------------------------------------------- S23 / S9: partner verification, click analytics
select t.become('super');
update public.profiles set role = 'partner', is_verified = false
  where id = (select id from t.ids where name = 'unverified');
insert into public.events (id, category, title) values ('3e000000-0000-0000-0000-000000000001', 'movie', 'Click film');
insert into public.venues (id, owner_id, name, venue_type)
select v.vid::uuid, (select id from t.ids where name = v.who), 'Venue ' || v.who, 'cinema'
from (values ('aaaaaaaa-0000-0000-0000-000000000001', 'partner_a'),
             ('aaaaaaaa-0000-0000-0000-000000000002', 'partner_b'),
             ('aaaaaaaa-0000-0000-0000-000000000003', 'unverified')) v(vid, who);
insert into public.showtimes (id, venue_id, event_id, start_time, booking_url)
select s.sid::uuid, s.vid::uuid, '3e000000-0000-0000-0000-000000000001', now() + interval '2 days', 'https://example.com/book'
from (values ('bbbbbbbb-0000-0000-0000-000000000001', 'aaaaaaaa-0000-0000-0000-000000000001'),
             ('bbbbbbbb-0000-0000-0000-000000000002', 'aaaaaaaa-0000-0000-0000-000000000002')) s(sid, vid);
insert into public.outbound_clicks (showtime_id) values
  ('bbbbbbbb-0000-0000-0000-000000000001'), ('bbbbbbbb-0000-0000-0000-000000000002');

select t.become('partner_a');
select t.chk('S9 partner reads only clicks on their own venues',
  (select count(*) = 1 and bool_and(showtime_id = 'bbbbbbbb-0000-0000-0000-000000000001') from public.outbound_clicks));
select t.become('unverified');
select t.chk('S9 unverified self-made partner reads no clicks', (select count(*) = 0 from public.outbound_clicks));
select t.become('attacker');
select t.chk('S9 plain user reads no clicks', (select count(*) = 0 from public.outbound_clicks));
select t.become('admin');
select t.chk('S9 admin reads all clicks', (select count(*) = 2 from public.outbound_clicks));

do $$ declare code text; begin
  perform t.become('unverified');
  begin
    insert into public.venues (owner_id, name, venue_type)
      values ((select id from t.ids where name = 'unverified'), 'Phish Kino', 'cinema');
    code := 'inserted';
  exception when others then code := sqlstate; end;
  perform t.become('super');
  perform t.chk('S23 unverified partner cannot create a venue (got ' || code || ')', code = '42501');
end $$;

do $$ declare code text; begin
  perform t.become('unverified');
  begin
    insert into public.showtimes (venue_id, event_id, start_time, booking_url)
      values ('aaaaaaaa-0000-0000-0000-000000000003', '3e000000-0000-0000-0000-000000000001',
              now() + interval '1 day', 'https://evil.example');
    code := 'inserted';
  exception when others then code := sqlstate; end;
  perform t.become('super');
  perform t.chk('S23 unverified partner cannot publish a showtime (got ' || code || ')', code = '42501');
end $$;

do $$ declare ok boolean; begin
  perform t.become('partner_a');
  insert into public.showtimes (venue_id, event_id, start_time, booking_url)
    values ('aaaaaaaa-0000-0000-0000-000000000001', '3e000000-0000-0000-0000-000000000001',
            now() + interval '3 days', 'https://example.com/ok');
  perform t.become('super');
  perform t.chk('S23 verified partner can still publish showtimes at their venue', true);
exception when others then
  perform t.become('super');
  perform t.chk('S23 verified partner can still publish showtimes (error: ' || sqlerrm || ')', false);
end $$;

---------------------------------------------------------------- account deletion grace period
select t.become('super');
insert into public.account_deletions (user_id, email)
select id, email from t.ids where name in ('victim', 'orphan');
select t.chk('deletion is scheduled 14 days out by default',
  (select bool_and(scheduled_for between now() + interval '13 days 23 hours' and now() + interval '14 days 1 hour')
   from public.account_deletions));

select t.become('victim');
select t.chk('user sees their own pending deletion', (select count(*) = 1 from public.account_deletions));
select t.become('attacker');
select t.chk('user cannot see anyone else''s pending deletion', (select count(*) = 0 from public.account_deletions));

do $$ declare c1 text; c2 text; c3 text; c4 text; begin
  perform t.become('victim');
  begin insert into public.account_deletions (user_id, email) values ((select id from t.ids where name = 'admin'), 'x@x.com');
    c1 := 'ok'; exception when others then c1 := sqlstate; end;
  begin update public.account_deletions set scheduled_for = now() + interval '365 days'; c2 := 'ok';
    exception when others then c2 := sqlstate; end;
  begin delete from public.account_deletions; c3 := 'ok'; exception when others then c3 := sqlstate; end;
  perform t.become('anon');
  begin perform count(*) from public.account_deletions; c4 := 'ok'; exception when others then c4 := sqlstate; end;
  perform t.become('super');
  perform t.chk('clients cannot insert, update or delete pending deletions directly (got ' || c1 || '/' || c2 || '/' || c3 || ')',
    c1 = '42501' and c2 = '42501' and c3 = '42501');
  perform t.chk('anon cannot read pending deletions (got ' || c4 || ')', c4 = '42501');
end $$;

do $$ declare r_attacker boolean; r_anon text; r_victim boolean; left_after int; begin
  perform t.become('attacker');
  r_attacker := public.restore_account();
  perform t.become('anon');
  begin perform public.restore_account(); r_anon := 'ok'; exception when others then r_anon := sqlstate; end;
  perform t.become('super');
  perform t.chk('restore_account does nothing for a user without a pending deletion',
    r_attacker = false and (select count(*) = 2 from public.account_deletions));
  perform t.chk('anon cannot call restore_account (got ' || r_anon || ')', r_anon = '42501');

  perform t.become('victim');
  r_victim := public.restore_account();
  perform t.become('super');
  select count(*) into left_after from public.account_deletions;
  perform t.chk('a user can restore their own account, and only their own',
    r_victim = true and left_after = 1
    and not exists (select 1 from public.account_deletions where email = 'victim@x.com'));
end $$;

delete from auth.users where id = (select id from t.ids where name = 'orphan');
select t.chk('hard-deleting the auth user removes its pending-deletion row',
  (select count(*) = 0 from public.account_deletions));

select t.become('super');

select case when ok then 'PASS' else 'FAIL' end as result, name from t.results order by n;
select count(*) filter (where not ok) as failures, count(*) as total from t.results;

rollback;
